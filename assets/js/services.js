const sectionsRoot = document.getElementById('service-sections');
if (sectionsRoot) {
    sections.forEach(section => {
        sectionsRoot.appendChild(createSection(section));
    });

    sectionsRoot.addEventListener('click', (event) => {
        const scrollButton = event.target.closest('[data-scroll-target]');
        if (!scrollButton) return;
        const targetId = scrollButton.dataset.scrollTarget;
        const direction = scrollButton.dataset.scrollDirection;
        const scroller = document.getElementById(targetId);
        if (!scroller) return;
        const offset = direction === 'left' ? -300 : 300;
        scroller.scrollBy({ left: offset, behavior: 'smooth' });
    });
}

document.addEventListener('click', (event) => {
    const serviceButton = event.target.closest('[data-service-key]');
    if (serviceButton) {
        showDetails(serviceButton.dataset.serviceKey);
    }
});

if (modal) {
    modal.addEventListener('click', (event) => {
        if (event.target === modal) {
            closeModal();
        }
    });
}

if (modalClose) {
    modalClose.addEventListener('click', closeModal);
}

document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeModal();
});
